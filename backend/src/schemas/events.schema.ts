import { z } from 'zod';

const eventCategories = [
  'Technology',
  'Artificial Intelligence',
  'Cybersecurity',
  'Hackathons',
  'Coding Competitions',
  'Workshops',
  'Seminars',
  'Conferences',
  'Cultural Events',
  'Sports',
  'Arts',
  'Club Meetings',
  'Career Events',
  'Internships and Opportunities',
  'Other',
  'academic',
  'social',
  'cultural',
  'workshop',
] as const;

export const createEventSchema = z.object({
  title: z.string().min(2, 'Title must be at least 2 characters').max(200),
  description: z.string().min(5, 'Description must be at least 5 characters'),
  summary: z.string().optional(),
  poster_url: z.string().optional(),
  start_date: z.string(),
  start_time: z.string().optional(),
  end_date: z.string().optional(),
  end_time: z.string().optional(),
  venue: z.string().optional(),
  is_online: z.boolean().optional(),
  meeting_url: z.string().optional(),
  category: z.string().optional(),
  category_id: z.string().optional(),
  college_id: z.string().optional(),
  organization_id: z.string().optional(),
  is_free: z.boolean().optional(),
  price: z.number().optional(),
  registration_type: z.enum(['internal', 'external', 'none']).optional(),
  registration_url: z.string().optional(),
  max_attendees: z.number().optional(),
  eligibility: z.any().optional(),
  status: z.enum(['draft', 'published', 'cancelled', 'completed']).optional(),
  visibility: z.enum(['public', 'college_only', 'invite_only']).optional(),
}).passthrough();

export const updateEventSchema = createEventSchema.partial();

export const eventQuerySchema = z.object({
  page: z.any().optional(),
  limit: z.any().optional(),
  status: z.string().optional(),
  category: z.string().optional(),
  collegeId: z.string().optional(),
  college_id: z.string().optional(),
  organizationId: z.string().optional(),
  search: z.string().optional(),
  dateFrom: z.string().optional(),
  dateTo: z.string().optional(),
  start_date: z.string().optional(),
  end_date: z.string().optional(),
  isOnline: z.any().optional(),
  isFree: z.any().optional(),
  sort: z.string().optional(),
}).passthrough();
